"""Generate supabase/seed.sql from the shared catalog in andes.core.seed.

    uv run python scripts/gen_seed_sql.py

The output is deterministic; re-running it on an unchanged catalog changes nothing.
"""

from __future__ import annotations

from pathlib import Path

from andes.core.seed import CATALOG

OUT = Path(__file__).resolve().parent.parent / "supabase" / "seed.sql"


def _q(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def render() -> str:
    rows = []
    for p in CATALOG:
        tags = "array[" + ", ".join(_q(t) for t in p["tags"]) + "]::text[]"
        rows.append(
            f"    ({_q(p['id'])}, {_q(p['destination'])}, {_q(p['name'])},\n"
            f"     {_q(p['description'])},\n"
            f"     {p['duration_days']}, {tags}, {p['base_rate']}, 'COP')"
        )
    return (
        "-- Generated by scripts/gen_seed_sql.py from andes.core.seed.CATALOG. Do not edit.\n"
        "insert into packages (id, destination, name, description, duration_days, tags,\n"
        "                      rate_per_person, currency)\nvalues\n"
        + ",\n".join(rows)
        + "\non conflict (id) do update set\n"
        "    destination = excluded.destination, name = excluded.name,\n"
        "    description = excluded.description, duration_days = excluded.duration_days,\n"
        "    tags = excluded.tags, rate_per_person = excluded.rate_per_person,\n"
        "    currency = excluded.currency, active = true;\n"
    )


if __name__ == "__main__":
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT}")
